import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';
import {
  createProgram,
  forEachChild,
  isObjectBindingPattern,
  isPropertyAssignment,
  isStringLiteralLike,
  parseJsonConfigFileContent,
  readConfigFile,
  sys,
  TypeFlags,
} from 'typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const configPath = resolve(root, 'apps/web/tsconfig.json');
const config = readConfigFile(configPath, sys.readFile);
const parsed = parseJsonConfigFileContent(
  config.config,
  sys,
  dirname(configPath),
);
const sources = {
  site: ['apps/web/src/lib/i18n/site.ts', 'SiteMessages'],
  admin: ['apps/web/src/lib/i18n/en.ts', 'en'],
  email: ['apps/api/src/domain/email/templates.ts', 'Templates'],
};
const program = createProgram(
  Object.values(sources).map(([path]) => resolve(root, path)),
  parsed.options,
);
const checker = program.getTypeChecker();
const manifest = {};
const sitePlaceholders = {};

for (const [scope, [path, name]] of Object.entries(sources)) {
  const source = program.getSourceFile(resolve(root, path));
  let declaration;

  const visit = (node) => {
    if (node.name?.getText(source) === name) declaration = node;

    forEachChild(node, visit);
  };

  visit(source);

  if (!declaration) throw new Error(`Missing catalog declaration: ${name}`);

  const type = checker.getTypeAtLocation(declaration);
  const messages = {};

  for (const property of checker.getPropertiesOfType(type)) {
    const value = checker.getTypeOfSymbolAtLocation(property, declaration);
    const signatures = value.getCallSignatures();

    if (signatures.length) {
      const signature = signatures[0];
      const parameters = signature.parameters.flatMap((parameter) => {
        const node = parameter.valueDeclaration;

        if (node && isObjectBindingPattern(node.name)) {
          return node.name.elements.map((element) => element.name.getText());
        }

        return [parameter.name];
      });
      const result = checker.getReturnTypeOfSignature(signature);
      const fields = checker.getPropertiesOfType(result);

      if (
        scope === 'email' &&
        fields.some((field) => field.name === 'subject')
      ) {
        for (const field of fields) {
          if (field.name === 'subject' || field.name === 'text') {
            messages[`${property.name}.${field.name}`] = parameters;
          }
        }
      } else {
        messages[property.name] = parameters;
      }

      if (scope === 'site') sitePlaceholders[property.name] = parameters;
    } else if (value.flags & TypeFlags.StringLike) {
      const node = property.valueDeclaration;
      const text =
        node &&
        isPropertyAssignment(node) &&
        isStringLiteralLike(node.initializer)
          ? node.initializer.text
          : '';

      messages[property.name] = [
        ...new Set(
          [...text.matchAll(/\{([A-Za-z_]\w*)\}/g)].map((match) => match[1]),
        ),
      ].sort();
    }
  }

  if (!Object.keys(messages).length) {
    throw new Error(`Empty catalog: ${scope}`);
  }

  manifest[scope] = Object.fromEntries(
    Object.entries(messages).sort(([left], [right]) =>
      left.localeCompare(right),
    ),
  );
}

const sorted = (messages) =>
  Object.fromEntries(
    Object.entries(messages).sort(([left], [right]) =>
      left.localeCompare(right),
    ),
  );
const outputs = {
  'packages/sdk/src/i18n-manifest.ts': `export const translationManifest = ${JSON.stringify(manifest)} as const;\n`,
  'apps/web/src/lib/i18n/site-params.ts': `// Generated by scripts/i18n-manifest.mjs.\n\n/** Placeholder names of the public catalog's parameterized messages, in argument order. */\nexport const SITE_PARAMS = ${JSON.stringify(sorted(sitePlaceholders))} as const;\n`,
};

for (const [path, source] of Object.entries(outputs)) {
  const output = await format(source, {
    parser: 'typescript',
    singleQuote: true,
    trailingComma: 'all',
  });
  const destination = resolve(root, path);

  if (process.argv.includes('--check')) {
    if ((await readFile(destination, 'utf8')) !== output) {
      throw new Error(`Translation manifest is stale: ${path}`);
    }
  } else {
    await writeFile(destination, output);
  }
}
